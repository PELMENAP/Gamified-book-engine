import { writeFileSync } from 'node:fs'
import { dirname, join, normalize } from 'node:path'
import { abs, codeFiles, exists, readText, rel, report, ROOT, walk } from './lib/repo.ts'
import { lex } from './lib/lex.ts'

interface DocmapConfig {
  indexPath: string
  largePath: string
  largeLimit: number
  budgets: Record<string, number>
  lineLimit: number
  lineLimitFiles: string[]
  checkedNames: string[]
  checkedPaths: string[]
  generated: string[]
  externalNames: string[]
  excludedPaths: string[]
}

interface PackageInfo {
  dir: string
  name: string
  deps: string[]
  lib: string[]
}

const config = JSON.parse(readText('tools/docmap.json')) as DocmapConfig
const EXPORT_RX = /^export\s+(?:declare\s+)?(?:async\s+)?(const|let|function|interface|type|class|enum)\s+([A-Za-z_$][\w$]*)/gm
const DECL_RX = /^(?:export\s+)?(?:async\s+)?(?:const|let|function|interface|type|class|enum)\s+([A-Za-z_$][\w$]*)/gm
const PATH_EXT = /\.(ts|tsx|md|json|yaml|yml|bmd|html|css|mjs|js|txt)$/

function globMatch(pattern: string, path: string): boolean {
  if (pattern.endsWith('/*')) return path.startsWith(pattern.slice(0, -1)) && !path.slice(pattern.length - 1).includes('/')
  if (pattern.includes('*')) {
    const [head, tail] = pattern.split('*')
    return path.startsWith(head ?? '') && path.endsWith(tail ?? '') && !path.slice((head ?? '').length).includes('/')
  }
  return path === pattern
}

function docFiles(patterns: readonly string[]): string[] {
  const all = walk('.', (p) => p.endsWith('.md'))
  return all.filter((p) => patterns.some((g) => globMatch(g, p)) && !config.excludedPaths.includes(p))
}

function packages(): PackageInfo[] {
  const out: PackageInfo[] = []
  for (const file of [...walk('packages', (p) => /^packages\/[^/]+\/package\.json$/.test(p)), ...walk('apps', (p) => /^apps\/[^/]+\/package\.json$/.test(p))]) {
    const pkg = JSON.parse(readText(file)) as { name: string; dependencies?: Record<string, string> }
    const dir = dirname(file)
    let lib: string[] = []
    if (exists(`${dir}/tsconfig.json`)) {
      const ts = JSON.parse(readText(`${dir}/tsconfig.json`)) as { compilerOptions?: { lib?: string[] } }
      lib = ts.compilerOptions?.lib ?? []
    }
    out.push({ dir, name: pkg.name, deps: Object.keys(pkg.dependencies ?? {}), lib })
  }
  return out
}

function lineAt(text: string, index: number): number {
  let line = 1
  for (let i = 0; i < index; i++) if (text.charCodeAt(i) === 10) line++
  return line
}

function generateIndex(): string {
  const lines: string[] = ['# Index', '', 'Generated by `node tools/docmap.ts gen`. Do not edit by hand.', '', '## Packages', '']
  lines.push('| Package | Path | Workspace deps | lib |', '|---|---|---|---|')
  for (const p of packages()) {
    const deps = p.deps.filter((d) => d.startsWith('@gbe/')).join(', ') || '—'
    lines.push(`| \`${p.name}\` | \`${p.dir}\` | ${deps} | ${p.lib.join(', ') || '—'} |`)
  }
  lines.push('', '## Exports', '', '| Name | Kind | File:line |', '|---|---|---|')
  const rows: string[] = []
  for (const file of codeFiles()) {
    if (file.startsWith('tools/') || file.includes('/test/')) continue
    const text = lex(readText(file)).code
    for (const m of text.matchAll(EXPORT_RX)) {
      rows.push(`| \`${m[2]}\` | ${m[1]} | \`${file}:${lineAt(text, m.index)}\` |`)
    }
  }
  rows.sort((a, b) => a.localeCompare(b))
  lines.push(...rows, '')
  return lines.join('\n')
}

function generateLarge(): string {
  const lines: string[] = ['# Large files', '', `Generated by \`node tools/docmap.ts gen\`. Files over ${config.largeLimit} lines with their declarations.`, '']
  let any = false
  for (const file of codeFiles()) {
    const source = readText(file)
    const count = source.split('\n').length
    if (count <= config.largeLimit) continue
    any = true
    lines.push(`## \`${file}\` (${count} lines)`, '')
    const text = lex(source).code
    for (const m of text.matchAll(DECL_RX)) lines.push(`- ${lineAt(text, m.index)}: \`${m[1]}\``)
    lines.push('')
  }
  if (!any) lines.push('No file is over the limit.', '')
  return lines.join('\n')
}

function codeCorpus(): string {
  const parts: string[] = []
  for (const file of codeFiles()) parts.push(readText(file))
  for (const file of walk('.', (p) => /(^|\/)(package\.json|[^/]+\.(json|yaml|html))$/.test(p) && !p.startsWith('docs/'))) parts.push(readText(file))
  return parts.join('\n')
}

function stripFences(text: string): string {
  return text.replace(/^```[\s\S]*?^```/gm, (block) => block.replace(/[^\n]/g, ' '))
}

function check(strict: boolean): string[] {
  const errors: string[] = []
  const external = new Set(config.externalNames)
  const corpus = codeCorpus()
  for (const doc of docFiles(config.checkedPaths)) {
    const raw = readText(doc)
    const text = stripFences(raw)
    const lines = raw.split('\n')
    for (const [pattern, limit] of Object.entries(config.budgets)) {
      if (globMatch(pattern, doc) && !config.generated.includes(doc) && lines.length > limit) errors.push(`${doc}: ${lines.length} lines, budget ${limit}`)
    }
    if (config.lineLimitFiles.some((g) => globMatch(g, doc)) && !config.generated.includes(doc)) {
      lines.forEach((l, i) => {
        if (l.length > config.lineLimit) errors.push(`${doc}:${i + 1}: line is ${l.length} chars, limit ${config.lineLimit}`)
      })
    }
    for (const m of text.matchAll(/\]\(([^)\s#]+)(#[^)]*)?\)/g)) {
      const target = m[1] ?? ''
      if (/^[a-z]+:/.test(target)) continue
      const resolved = rel(normalize(join(ROOT, dirname(doc), target)))
      if (!exists(resolved)) errors.push(`${doc}: link target does not exist: ${target}`)
    }
    const checkNames = config.checkedNames.some((g) => globMatch(g, doc)) && !config.generated.includes(doc)
    for (const m of text.matchAll(/`([^`\n]+)`/g)) {
      const token = (m[1] ?? '').trim()
      if (/\s|[*<>{}]/.test(token)) continue
      const path = token.replace(/:\d+$/, '').replace(/\/$/, '')
      if (/^(packages|apps|tools|docs|book|\.github)\//.test(path) || (PATH_EXT.test(path) && path.includes('/'))) {
        if (!exists(path)) errors.push(`${doc}: path does not exist: ${token}`)
        continue
      }
      if (!checkNames) continue
      const name = token.replace(/\(\)$/, '')
      if (!/^[A-Za-z_$][\w$]*$/.test(name)) continue
      if (!/[A-Z]/.test(name) || external.has(name)) continue
      if (!new RegExp(`(?<![\\w$])${name.replace(/\$/g, '\\$')}(?![\\w$])`).test(corpus)) {
        errors.push(`${doc}: name does not occur in the code: ${token}`)
      }
    }
  }
  if (strict) {
    if (!exists(config.indexPath) || readText(config.indexPath) !== generateIndex()) errors.push(`${config.indexPath}: stale; run node tools/docmap.ts gen`)
    if (!exists(config.largePath) || readText(config.largePath) !== generateLarge()) errors.push(`${config.largePath}: stale; run node tools/docmap.ts gen`)
  }
  return errors
}

const command = process.argv[2]
if (command === 'gen') {
  writeFileSync(abs(config.indexPath), generateIndex())
  writeFileSync(abs(config.largePath), generateLarge())
  console.log(`docmap: wrote ${config.indexPath}, ${config.largePath}`)
} else if (command === 'check') {
  report('docmap', check(process.argv.includes('--strict')))
} else {
  console.error('usage: node tools/docmap.ts gen | check [--strict]')
  process.exitCode = 2
}
